// Renders tools/hud/render.html with headless Edge/Chrome and writes each [data-sprite] element to
// assets/hud/<name>.png, plus client/hud_assets.lua with each sprite's pixel size.
//
//   node tools/hud/build.mjs
//
// Set BROWSER to a chrome/msedge executable if it is not found automatically.

import { spawn } from 'node:child_process';
import { existsSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SCALE = 3; // render at 3x so the sprites stay sharp at 1440p/4K
const PORT = 9333;

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');

const browser = [
    process.env.BROWSER,
    'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
    'C:/Program Files/Microsoft/Edge/Application/msedge.exe',
    'C:/Program Files/Google/Chrome/Application/chrome.exe',
].find((p) => p && existsSync(p));

if (!browser) throw new Error('No Edge or Chrome found; set BROWSER to its executable');

const profile = mkdtempSync(join(tmpdir(), 'ox_doorlock_hud-'));
const proc = spawn(browser, ['--headless=new', `--remote-debugging-port=${PORT}`, `--user-data-dir=${profile}`, '--hide-scrollbars', 'about:blank']);

async function getTarget() {
    for (let i = 0; i < 50; i++) {
        try {
            const list = await (await fetch(`http://127.0.0.1:${PORT}/json/list`)).json();
            const page = list.find((t) => t.type === 'page');
            if (page) return page;
        } catch {}
        await new Promise((r) => setTimeout(r, 200));
    }
    throw new Error('Browser did not start');
}

const ws = new WebSocket((await getTarget()).webSocketDebuggerUrl);
await new Promise((r) => ws.addEventListener('open', r, { once: true }));

let nextId = 0;
const pending = new Map();
const listeners = new Map();

ws.addEventListener('message', ({ data }) => {
    const msg = JSON.parse(data);
    if (msg.id && pending.has(msg.id)) {
        const { res, rej } = pending.get(msg.id);
        pending.delete(msg.id);
        msg.error ? rej(new Error(msg.error.message)) : res(msg.result);
    } else if (msg.method && listeners.has(msg.method)) {
        listeners.get(msg.method)();
        listeners.delete(msg.method);
    }
});

const send = (method, params = {}) => new Promise((res, rej) => {
    const id = ++nextId;
    pending.set(id, { res, rej });
    ws.send(JSON.stringify({ id, method, params }));
});

const once = (method) => new Promise((r) => listeners.set(method, r));

try {
    await send('Page.enable');
    await send('Emulation.setDeviceMetricsOverride', { width: 800, height: 600, deviceScaleFactor: SCALE, mobile: false });
    await send('Emulation.setDefaultBackgroundColorOverride', { color: { r: 0, g: 0, b: 0, a: 0 } });

    const loaded = once('Page.loadEventFired');
    await send('Page.navigate', { url: pathToFileURL(join(here, 'render.html')).href });
    await loaded;

    const { result } = await send('Runtime.evaluate', {
        awaitPromise: true,
        returnByValue: true,
        expression: `document.fonts.ready.then(() => [...document.querySelectorAll('[data-sprite]')].map((el) => {
            const r = el.getBoundingClientRect();
            return { name: el.dataset.sprite, x: r.x, y: r.y, w: r.width, h: r.height };
        }))`,
    });

    const sizes = [];

    for (const s of result.value) {
        const { data } = await send('Page.captureScreenshot', {
            format: 'png',
            clip: { x: s.x, y: s.y, width: s.w, height: s.h, scale: 1 },
        });

        writeFileSync(join(root, 'assets/hud', `${s.name}.png`), Buffer.from(data, 'base64'));
        sizes.push(`    ${s.name} = { ${Math.round(s.w)}, ${Math.round(s.h)} },`);
        console.log(`assets/hud/${s.name}.png  ${s.w}x${s.h} @${SCALE}x`);
    }

    writeFileSync(join(root, 'client/hud_assets.lua'),
        `-- Generated by tools/hud/build.mjs: sprite sizes in 1080p px (width, height)\nHudAssets = {\n${sizes.join('\n')}\n}\n`);
} finally {
    ws.close();
    proc.kill();
    setTimeout(() => rmSync(profile, { recursive: true, force: true }), 500);
}
